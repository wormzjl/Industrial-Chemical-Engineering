/** Draws text at an integer scale; returns its width. */
export function text(canvas, x, y, s, c, scale = 2) {
  let cx = x;
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    for (let r = 0; r < 7; r++) for (let q = 0; q < 5; q++) if (g[r * 5 + q] === '1') canvas.rect(cx + q * scale, y + r * scale, scale, scale, c);
    cx += 6 * scale;
  }
  return cx - x;
}
