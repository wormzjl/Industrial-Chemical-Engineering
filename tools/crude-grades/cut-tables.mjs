// Entry point 1: the twelve cut liquid-viscosity tables (E14), in the log_table schema of crude_pc05.json.
// Writes <out>/cut-viscosity/crude_pcNN.viscosity.liquid.json (the block that replaces `viscosity.liquid`) and
// <out>/cut-viscosity/summary.json. Run: node tools/crude-grades/cut-tables.mjs
import path from 'node:path';
import {loadComponents, OUT, evalTable} from './lib/materials.mjs';
import {twu1985, twuDynamic, rackettDensity, SG} from './lib/correlations.mjs';
import {writeJson, isMain} from './lib/out.mjs';

export const REVISION = 'twu-1985-d341-r1';
export const SOURCE = 'Twu, Ind. Eng. Chem. Process Des. Dev. 24 (1985) 1287: kinematic viscosity at 100 F and 210 F from this record\'s '
  + 'normal boiling point and standard density (n-alkane reference plus specific-gravity correction), continued in temperature by the '
  + 'ASTM D341 two-point (Walther) form; dynamic viscosity = kinematic x Rackett saturated-liquid density (Spencer-Danner, Yamada-Gunn '
  + 'Z_RA from this record\'s acentric factor) anchored at the standard density, held at its critical value above Tc; capped at 1e12 Pa s. '
  + 'Correlation estimate, no measured data; extrapolated beyond the correlation\'s fitted range for SG >= 1.0 (crude_pc11, crude_pc12). '
  + 'Generated by tools/crude-grades/cut-tables.mjs.';

export function cutTables(comps = loadComponents()) {
  const template = comps.find(c => c.name === 'crude_pc05').record.viscosity.liquid;
  const out = {};
  for (const c of comps.filter(c => !c.light)) {
    const nodes = template.temperatures_kelvin;
    const block = {};
    for (const k of Object.keys(template)) block[k] = template[k];
    block.coefficients = nodes.map(T => twuDynamic(c, T));
    block.temperatures_kelvin = nodes;
    block.estimated = true; block.revision = REVISION; block.source = SOURCE;
    out[c.name] = block;
  }
  return out;
}

if (isMain(import.meta.url)) {
  const comps = loadComponents(), tables = cutTables(comps), summary = [];
  for (const c of comps.filter(c => !c.light)) {
    const b = tables[c.name], tb = {t: b.temperatures_kelvin, c: b.coefficients};
    writeJson(path.join(OUT, 'cut-viscosity', c.name + '.viscosity.liquid.json'), b);
    const {v100, v210} = twu1985(c.Tb, SG(c.rho60));
    const row = {cut: c.name, nbp_kelvin: c.Tb, sg: SG(c.rho60), twu_cst_100F: v100, twu_cst_210F: v210};
    for (const T of [288.15, 293.15, 313.15, 373.15, 500, 700, 900]) {
      row['mu_mpas_' + T] = evalTable(tb, T) * 1e3;
      row['ratio_to_dalia_' + T] = evalTable(tb, T) / evalTable(c.liq, T);
    }
    row.rackett_kg_m3_313 = rackettDensity(c, 313.15); row.rackett_kg_m3_900 = rackettDensity(c, 900);
    row.capped_nodes = b.coefficients.filter(v => v >= 1e12).length;
    summary.push(row);
    console.log(c.name.padEnd(11), `313 K ${row['mu_mpas_313.15'].toPrecision(4)} mPa s (x${row['ratio_to_dalia_313.15'].toPrecision(3)} Dalia)`,
      ` 373 K ${row['mu_mpas_373.15'].toPrecision(4)} (x${row['ratio_to_dalia_373.15'].toPrecision(3)})`, ` 900 K ${row.mu_mpas_900.toPrecision(3)}`, ` capped nodes ${row.capped_nodes}`);
  }
  writeJson(path.join(OUT, 'cut-viscosity', 'summary.json'), {revision: REVISION, source: SOURCE, cuts: summary});
}
