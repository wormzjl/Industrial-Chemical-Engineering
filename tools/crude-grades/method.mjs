// Entry point 4: the proposed one-term `liquid_mixture` block for methods/crude_pr78.json (E12), from <out>/g-fit.json.
// Writes <out>/crude_pr78.liquid_mixture.json: the proposed shape, and the equivalent block the current Java reads.
// Run after fit-g.mjs: node tools/crude-grades/method.mjs
import fs from 'node:fs';
import path from 'node:path';
import {OUT, CUTS} from './lib/materials.mjs';
import {writeJson, isMain} from './lib/out.mjs';

export const REVISION = 'eccc-cut-pair-r1';
if (isMain(import.meta.url)) {
  const fit = JSON.parse(fs.readFileSync(path.join(OUT, 'g-fit.json'), 'utf8'));
  // E15 (orchestrator, 2026-11-04): G from the crudes the shared cuts represent (rule R5), not the full set, whose
  // non-representable crudes would make G absorb the cut basis's density error. The full-set value is kept in `fit`.
  const G = +fit.representable.G.toFixed(4), s = fit.representable.stats;
  const source = `Cut-pair term delta = G (x_cut^2 - sum x_i^2) over crude_pc01..12, G fitted by least squares in ln mu to ${s.points} ECCC whole-crude `
    + `viscosities of the ${s.crudes} fresh crudes the shared cuts represent (rule R5: API on the cuts within 3 of measured) at 0 and 15 C (rms ln residual ${s.rms_ln.toFixed(3)}), cut tables twu-1985-d341-r1; Environment and Climate Change `
    + 'Canada, Crude Oil and Petroleum Product Database 2021-01-22, Open Government Licence - Canada. Generated by tools/crude-grades.';
  writeJson(path.join(OUT, 'crude_pr78.liquid_mixture.json'), {
    proposed: {liquid_mixture: {type: 'cut_pair_v1', coefficient: G, components: CUTS, source, revision: REVISION}},
    current_java_equivalent: {
      note: 'LiquidMixtureCorrection (symmetric_pair_groups_v1) gives exactly delta = G (x_cut^2 - sum x_i^2) with coefficients [G, 0, 0, 0] and, on each crude_pc record, liquid_mixture_descriptor {participation 1, residue_retention 0, activation_slope 0}: fh = eh = ea = 0, and reference_kelvin / slope_cap_kelvin then have no effect.',
      liquid_mixture: {type: 'symmetric_pair_groups_v1', coefficients: [G, 0, 0, 0], reference_kelvin: 323.15, slope_cap_kelvin: 373.15, source, revision: REVISION},
      liquid_mixture_descriptor_each_cut: {participation: 1, residue_retention: 0, activation_slope: 0},
    },
    fit: {chosen: 'representable subset (E15)', G_representable_subset: fit.representable.G, representable_stats: s, G_full: fit.full.G, full_stats: fit.full.stats},
  });
  console.log('G', G, 'revision', REVISION);
}
